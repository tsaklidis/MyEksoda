#!/usr/bin/env python3
"""Generate docs/codemap/SYMBOLS.md: every Kotlin file with its declarations and line numbers.

Read (or grep) this index instead of opening source files to find where something
lives. Regenerate after adding, moving or renaming declarations:

    make codemap        # or: python3 scripts/codemap.py

Only non-private declarations at file level and one level inside a class are listed.
Data-class constructor properties and `override` members are skipped (they are noise here).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "codemap" / "SYMBOLS.md"
SKIP_DIRS = {"build", ".gradle", ".git", ".idea", ".kotlin", "testdata"}
MAX_LINE = 120

DECL = re.compile(
    r"^(?P<indent> {0,4})"
    r"(?P<mods>(?:@\w+(?:\([^)]*\))?\s+)*(?:(?:public|internal|protected|abstract|open|data|"
    r"sealed|enum|annotation|value|inline|const|lateinit|suspend|operator|infix|tailrec|"
    r"companion|fun)\s+)*)"
    r"(?P<kind>class|interface|object|fun|val|var|typealias)\b(?P<rest>.*)$"
)
PORT = re.compile(r"^//\s*(Port of .*)$")


def module_of(path: Path) -> str:
    parts = path.relative_to(ROOT).parts
    if parts[0] in ("core", "feature"):
        return f"{parts[0]}:{parts[1]}"
    return parts[0]


def short(rel: str) -> str:
    return rel  # the real path, so it can be opened as is


def declarations(lines: list[str]) -> list[str]:
    out = []
    in_type = False  # is the enclosing top-level declaration a class, interface or object?
    for number, line in enumerate(lines, 1):
        match = DECL.match(line)
        if not match:
            continue
        indent = match.group("indent")
        if not indent:
            in_type = match.group("kind") in ("class", "interface", "object")
        elif not in_type:
            continue  # a local inside a top-level function
        mods = match.group("mods")
        if "private" in line.split(match.group("kind"))[0] or "override" in mods:
            in_type = in_type and bool(indent)  # members of a private type are private too
            continue
        text = line.strip()
        if indent and match.group("kind") in ("val", "var") and text.endswith(","):
            continue  # constructor property
        if indent and match.group("kind") == "fun" and "companion" in mods:
            continue
        text = re.sub(r"\s*\{\s*$", "", text)
        text = re.sub(r"@\w+(\([^)]*\))?\s+", "", text)
        text = text.replace("public ", "")
        if len(text) > MAX_LINE:
            text = text[: MAX_LINE - 1] + "…"
        out.append(f"{number}{'  ' if indent else ' '}{text}")
    return out


def main() -> int:
    files = sorted(
        p
        for p in ROOT.rglob("*.kt")
        if not SKIP_DIRS.intersection(p.relative_to(ROOT).parts)
        and "/src/" in p.as_posix()
    )
    by_module: dict[str, list[str]] = {}
    total = 0
    for path in files:
        lines = path.read_text(encoding="utf-8").splitlines()
        total += len(lines)
        rel = path.relative_to(ROOT).as_posix()
        header = next((m.group(1) for l in lines[:3] if (m := PORT.match(l))), "")
        block = [f"### {short(rel)} ({len(lines)})" + (f" — {header}" if header else "")]
        block += declarations(lines)
        by_module.setdefault(module_of(path), []).append("\n".join(block))

    out = [
        "# Symbol index (generated)",
        "",
        "Generated by `scripts/codemap.py`; do not edit. Regenerate with `make codemap`.",
        f"{len(files)} Kotlin files, {total} lines. Format: `line kind signature`; two spaces",
        "after the line number = member of the class above. `(n)` after a path = its line count.",
        "Grep this file (`rtk grep -n 'Name' docs/codemap/SYMBOLS.md`) before opening sources.",
        "",
    ]
    for module in sorted(by_module):
        out.append(f"## {module}\n")
        out.append("\n\n".join(by_module[module]))
        out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
